"""C: registry -> tier constants (design §3.1), mirroring urim-ts src/providers.ts. The repo registry is EXAMPLE DATA.

The registry stays plain JSON data (it is read, checked and turned into source text, never used as objects), so its
camelCase member is named through ``json_name`` like every other wire key.
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from typing import Any

from .boundary import json_name
from .jsonfmt import js_string, stringify

_CAMPS = frozenset({"systemone", "decisions"})
_QTYPES = frozenset({"noul", "choice", "score"})
_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_QT = json_name("question_types")


def _pascal(s: str) -> str:
    return "".join(w[0].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", s) if w)


def constant_name(model: str, version: str) -> str:
    return f"{_pascal(model)}_{re.sub(r'[^A-Za-z0-9]', '_', version)}"


def parse_registry(v: Any) -> Mapping[str, Any]:
    """Checks the shape urim-ts checks, with the same messages; returns the registry unchanged."""

    def fail(m: str) -> TypeError:
        return TypeError(f"registry: {m}")

    if not (
        isinstance(v, dict)
        and isinstance(v.get("notice"), str)
        and isinstance(v.get("example"), bool)
        and isinstance(v.get("providers"), list)
    ):
        raise fail("needs {notice, example, providers[]}")
    for p in v["providers"]:
        if not (
            isinstance(p.get("provider"), str)
            and isinstance(p.get("namespace"), str)
            and _IDENT.match(p["namespace"])
            and p.get("camp") in _CAMPS
            and isinstance(p.get("models"), list)
        ):
            raise fail(f"bad provider {p.get('provider')}")
        names = [constant_name(m["model"], m["version"]) for m in p["models"]]
        if len(set(names)) != len(names):
            raise fail(f"duplicate constant in {p['namespace']}")
        for m in p["models"]:
            if not all(q in _QTYPES for q in m[_QT]):
                raise fail(f"bad questionTypes for {m['model']}")
    return v


def _header(r: Mapping[str, Any], source: str, comment: str) -> list[str]:
    return [
        f"{comment} GENERATED by `urim providers` from {source}. Do not edit by hand.",
        *([f"{comment} {r['notice']}"] if r["example"] else []),
    ]


def generate_providers_ts(r: Mapping[str, Any], *, source: str, import_from: str | None = None) -> str:
    """Byte-identical to urim-ts generateProviders."""
    lines = [*_header(r, source, "//"), f'import {{ tier }} from "{import_from or "./define.ts"}";', ""]
    for p in r["providers"]:
        lines.append(f"export const {p['namespace']} = Object.freeze({{")
        for m in p["models"]:
            lines.append(
                f"  {constant_name(m['model'], m['version'])}: tier({{ provider: {js_string(p['provider'])}, "
                f"model: {js_string(m['model'])}, version: {js_string(m['version'])}, "
                f"camp: {js_string(p['camp'])}, questionTypes: {stringify(list(m[_QT]))} }}),"
            )
        lines += ["});", ""]
    return "\n".join(lines)


def generate_providers_py(r: Mapping[str, Any], *, source: str, import_from: str | None = None) -> str:
    """The same constants as a Python module: one class per namespace, one ``tier`` attribute per model."""
    lines = [*_header(r, source, "#"), f"from {import_from or 'urim'} import tier", ""]
    for p in r["providers"]:
        lines += ["", f"class {p['namespace']}:"]
        for m in p["models"]:
            qts = ", ".join(js_string(q) for q in m[_QT])
            lines.append(
                f"    {constant_name(m['model'], m['version'])} = tier(provider={js_string(p['provider'])}, "
                f"model={js_string(m['model'])}, version={js_string(m['version'])}, "
                f"camp={js_string(p['camp'])}, question_types=({qts},))"
            )
    return "\n".join(lines) + "\n"
