// C: registry -> `urim/providers` tier constants (design §3.1). The registry in this repo is EXAMPLE DATA.
import type { Camp, QuestionType } from "./types.ts";

export type Registry = {
  readonly notice: string; readonly example: boolean;
  readonly providers: readonly { readonly provider: string; readonly namespace: string; readonly camp: Camp;
    readonly models: readonly { readonly model: string; readonly version: string; readonly questionTypes: readonly QuestionType[] }[] }[];
};
const CAMPS = new Set(["systemone", "decisions"]);
const QTYPES = new Set(["noul", "choice", "score"]);
const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;

const pascal = (s: string) => s.split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0]!.toUpperCase() + w.slice(1)).join("");
export const constantName = (model: string, version: string) => `${pascal(model)}_${version.replace(/[^A-Za-z0-9]/g, "_")}`;

export const parseRegistry = (v: unknown): Registry => {
  const fail = (m: string): never => { throw new TypeError(`registry: ${m}`); };
  const r = v as Registry;
  if (typeof r?.notice !== "string" || typeof r.example !== "boolean" || !Array.isArray(r.providers)) fail("needs {notice, example, providers[]}");
  for (const p of r.providers) {
    if (typeof p.provider !== "string" || !IDENT.test(p.namespace) || !CAMPS.has(p.camp) || !Array.isArray(p.models)) fail(`bad provider ${p.provider}`);
    const names = p.models.map((m) => constantName(m.model, m.version));
    if (new Set(names).size !== names.length) fail(`duplicate constant in ${p.namespace}`);
    for (const m of p.models) if (!m.questionTypes.every((q) => QTYPES.has(q))) fail(`bad questionTypes for ${m.model}`);
  }
  return r;
};

export const generateProviders = (r: Registry, opts: { readonly source: string; readonly importFrom?: string }): string => {
  const lines = [
    `// GENERATED by \`urim providers\` from ${opts.source}. Do not edit by hand.`,
    ...(r.example ? [`// ${r.notice}`] : []),
    `import { tier } from "${opts.importFrom ?? "./define.ts"}";`, "",
  ];
  for (const p of r.providers) {
    lines.push(`export const ${p.namespace} = Object.freeze({`);
    for (const m of p.models) {
      lines.push(`  ${constantName(m.model, m.version)}: tier({ provider: ${JSON.stringify(p.provider)}, model: ${JSON.stringify(m.model)}, `
        + `version: ${JSON.stringify(m.version)}, camp: ${JSON.stringify(p.camp)}, questionTypes: ${JSON.stringify(m.questionTypes)} }),`);
    }
    lines.push("});", "");
  }
  return lines.join("\n");
};
